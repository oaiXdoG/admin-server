create table if not exists ops_host (
    id bigint generated by default as identity primary key,
    ip varchar(64) not null,
    hostname varchar(128) not null default '',
    remark varchar(128) not null default '',
    last_seen_at bigint not null default 0,
    created_at bigint not null,
    updated_at bigint not null,
    constraint uk_ops_host_ip unique (ip)
);

create table if not exists ops_app (
    id bigint generated by default as identity primary key,
    name varchar(64) not null,
    host_id bigint not null,
    dir varchar(256) not null,
    remark varchar(128) not null default '',
    deployed_at bigint not null default 0,
    created_at bigint not null,
    updated_at bigint not null,
    constraint uk_ops_app_dir unique (host_id, dir),
    constraint fk_ops_app_host foreign key (host_id) references ops_host (id)
);

