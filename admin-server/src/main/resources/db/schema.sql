-- 初始角色（可在「角色管理」里修改或删除）。菜单按 route_name 选取，目录下的子菜单和按钮一起分配，上级目录随之分配。
insert into role (name, code, description, status, built_in, created_at, updated_at) values
    ('前端', 'FRONTEND', '数据查询', 1, false, 0, 0),
    ('后端', 'BACKEND', '数据中心', 1, false, 0, 0),
    ('测试', 'TESTER', '数据查询', 1, false, 0, 0),
    ('运营', 'OPERATOR', '数据查询', 1, false, 0, 0)
on conflict do nothing;

with recursive grant_root(code, route_name) as (
    values ('FRONTEND', 'data_query'),
           ('BACKEND', 'data'),
           ('TESTER', 'data_query'),
           ('OPERATOR', 'data_query')
), granted(code, id, parent_id) as (
    select g.code, m.id, m.parent_id from grant_root g join menu m on m.route_name = g.route_name
    union
    select g.code, m.id, m.parent_id from granted g join menu m on m.parent_id = g.id
), ancestor(code, id, parent_id) as (
    select code, id, parent_id from granted
    union
    select a.code, m.id, m.parent_id from ancestor a join menu m on m.id = a.parent_id
)
insert into role_menu (role_id, menu_id)
select r.id, a.id from ancestor a join role r on r.code = a.code
on conflict do nothing;

